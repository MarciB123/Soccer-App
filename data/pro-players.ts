// ─── MATCH FUNCTION ───────────────────────────────────────────────────────
// Uses the static PLAYERS_BY_POSITION table — position-correct players GUARANTEED.
// Playing style and body type sort the results so the closest match appears first.
export function matchProPlayers(
  subPosition: string | null,
  playingStyle: string | null,
  bodyType: BodyType | null
): ProPlayer[] {
  if (!subPosition) return []

  const slugs = PLAYERS_BY_POSITION[subPosition] || []
  const players = slugs
    .map((slug) => PRO_PLAYERS.find((p) => p.slug === slug))
    .filter(Boolean) as ProPlayer[]

  // Sort within the position-correct pool by style/body match (closest first)
  return players.sort((a, b) => {
    const scoreA =
      (playingStyle && a.playStyles.includes(playingStyle) ? 3 : 0) +
      (bodyType && a.bodyTypes.includes(bodyType) ? 2 : 0)
    const scoreB =
      (playingStyle && b.playStyles.includes(playingStyle) ? 3 : 0) +
      (bodyType && b.bodyTypes.includes(bodyType) ? 2 : 0)
    return scoreB - scoreA
  })
}
